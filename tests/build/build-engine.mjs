import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../..');
const output = path.join(root, 'src/scientific_calculator/static/scientific_calculator');
const result = await build({absWorkingDir: root, entryPoints:['tests/build/math-engine.source.mjs'], bundle:true, minify:true, platform:'browser', target:'es2022', format:'iife', globalName:'ScientificCalculatorEngine', write:false, metafile:true, legalComments:'inline', footer:{js:'if(typeof module!=="undefined"&&module.exports&&typeof document==="undefined")module.exports=ScientificCalculatorEngine;'}});
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const files = Object.values(result.metafile.outputs).flatMap(o => Object.entries(o.inputs).filter(([,v]) => v.bytesInOutput > 0).map(([f])=>f)).sort();
if(files.some(f=>f.includes('csparse'))) throw new Error('Unexpected CSparse in numerical bundle');
const names = [...new Set(files.filter(f=>f.startsWith('node_modules/')).map(f=>f.split('/').slice(1, f.split('/')[1].startsWith('@') ? 3 : 2).join('/')))].sort();
let notices = 'Locally bundled numerical engine; generated by tests/build/build-engine.mjs.\n';
const packages = [];
for(const name of names) {
  const dir = path.join(root,'node_modules',name);
  const pkg = JSON.parse(await readFile(path.join(dir,'package.json'),'utf8'));
  let license;
  for(const file of ['LICENSE','LICENSE.md','LICENCE.md','LICENSE.txt']) { try {license = await readFile(path.join(dir,file),'utf8'); break;} catch {} }
  if(!license) throw new Error(`Missing license for ${name}`);
  packages.push({name,version:pkg.version,license:pkg.license});
  notices += `\n===== ${name} ${pkg.version} (${pkg.license}) =====\n${license}\n`;
  try {notices += await readFile(path.join(dir,'NOTICE'),'utf8');} catch {}
}
const bundle = result.outputFiles[0].contents;
notices = notices.replace(/\r\n/g, '\n').trimEnd() + '\n';
const metadata = JSON.stringify({mathjs:'15.2.0',sourceSha256:hash(await readFile(path.join(root,'tests/build/math-engine.source.mjs'))),bundleSha256:hash(bundle),packages,compiledInputs:files},null,2)+'\n';
for(const [file,bytes] of [['math-engine.js',bundle],['math-engine.json',metadata],['THIRD_PARTY_NOTICES.txt',notices]]) {
  const destination=path.join(output,file);
  if(process.argv.includes('--check')) {if(hash(await readFile(destination))!==hash(bytes)) throw new Error(`Stale numerical asset: ${file}`);}
  else await writeFile(destination,bytes);
}
console.log(`Verified Math.js 15.2.0 numerical bundle (${bundle.length} bytes), ${packages.length} dependency notices`);
